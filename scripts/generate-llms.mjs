// =====================================================
// scripts/generate-llms.mjs
// Publisher E-commerce Platform
// =====================================================
// Author: Lewei Rong
//
// Generates the crawler- and LLM-readable files for acerbooks.ca from the
// Supabase `books` table, so search engines and AI agents can read the
// catalogue without running JavaScript:
//
//   book/<slug>.html — one real page per book (HTTP 200 instead of 404.html).
//                      Built from index.html: same SPA, plus the book's <title>,
//                      meta/Open Graph tags, schema.org Book JSON-LD and the
//                      detail page pre-filled. main.js re-renders it as usual.
//   books.html       — /books with a plain list of links to every book page
//   sitemap.xml      — /, /books and every book page
//   books.md         — full catalogue in Markdown (llms.txt v2, https://llmstxt.org/)
//   llms.txt         — short overview that links to books.md and about.md
//   robots.txt       — only created if missing (points to sitemap.xml)
//   .nojekyll        — stops GitHub Pages (Jekyll) from converting books.md
//
// about.md is written by hand and is not touched by this script.
// Pages in book/ that this script generated earlier are deleted when the book
// no longer exists. Hand-made files in book/ are never touched.
//
// Usage (from the repository root):
//   SUPABASE_URL=... SUPABASE_ANON_KEY=... node scripts/generate-llms.mjs
//   BOOKS_JSON=sample-books.json node scripts/generate-llms.mjs   ← local test without Supabase
//
// Run automatically by .github/workflows/update-llms-txt.yml
// =====================================================

import { readFile, writeFile, access, mkdir, readdir, unlink } from 'node:fs/promises';

// ── Site settings ─────────────────────────────────────────────────────────────
const SITE = 'https://acerbooks.ca';
const OUTPUT_DIR = process.env.OUTPUT_DIR || '.';
const TEMPLATE_FILE = `${OUTPUT_DIR}/index.html`;
const GENERATED_MARKER = '<!-- generated by scripts/generate-llms.mjs — do not edit by hand -->';

// Same series as the "All Series" filter in index.html, in display order
const SERIES = ['Acer Series', 'Acer Novels', 'Acer Essays', 'Acer Poetry', "Children's Art"];
const OTHER_SERIES = 'Other titles';

const DESCRIPTION_MAX_CHARS = 1200;   // books.md only; the book page has the full text
const META_DESCRIPTION_MAX_CHARS = 160;

// Columns read from the `books` table (anon key — same public read access as the website)
const BOOK_COLUMNS = [
    'id', 'title', 'title_fr', 'author', 'author_fr', 'price', 'price_hardcover',
    'cover', 'isbn', 'publisher', 'pub_date', 'pages', 'language', 'categories',
    'description', 'author_bio', 'stock_status', 'amazon_url',
].join(',');

// ── Load books ────────────────────────────────────────────────────────────────
async function loadBooks() {
    // Local test mode: read books from a JSON file instead of Supabase
    if (process.env.BOOKS_JSON) {
        return JSON.parse(await readFile(process.env.BOOKS_JSON, 'utf8'));
    }

    const url = (process.env.SUPABASE_URL || '').replace(/\/+$/, '');
    const key = process.env.SUPABASE_ANON_KEY || '';
    if (!url || !key) {
        throw new Error('SUPABASE_URL and SUPABASE_ANON_KEY must be set (see constants.js for the values).');
    }

    const res = await fetch(`${url}/rest/v1/books?select=${BOOK_COLUMNS}`, {
        headers: { apikey: key, Authorization: `Bearer ${key}` },
    });
    if (!res.ok) {
        throw new Error(`Supabase request failed: ${res.status} ${await res.text()}`);
    }
    return res.json();
}

// ── Book slug — same rules as toSlugAsync() in routing.js ─────────────────────
// Mixed titles use their Latin part; Chinese-only titles use pinyin.
let pinyinFn = null;
try {
    ({ pinyin: pinyinFn } = await import('pinyin-pro'));
} catch {
    console.warn('pinyin-pro not installed — Chinese-only titles get no static page.');
}

function cleanSlug(text) {
    return text.toLowerCase().replace(/\s+/g, '-').replace(/-+/g, '-').replace(/^-|-$/g, '').trim();
}

// Returns null when no slug can be built (the website would also fail to route it)
function bookSlug(title) {
    if (!title) return null;
    const cleaned = title.replace(/[：:·•—–()\[\]《》「」『』【】]/g, ' ').trim();
    const latinPart = cleanSlug(cleaned
        .replace(/[\u3000-\u9fff\uac00-\ud7af\uf900-\ufaff]/g, ' ')
        .replace(/[^a-zA-Z0-9\s-]/g, ' '));
    if (latinPart) return latinPart;

    const cjkOnly = cleaned.replace(/[^\u3000-\u9fff\uac00-\ud7af\uf900-\ufaff]/g, '');
    if (!cjkOnly || !pinyinFn) return null;
    return cleanSlug(pinyinFn(cjkOnly, { toneType: 'none', type: 'array' }).join('-')) || null;
}

function bookPageUrl(book) {
    return book.slug ? `${SITE}/book/${book.slug}` : `${SITE}/books`;
}

// ── Field formatting ──────────────────────────────────────────────────────────
function toNumber(value) {
    const n = parseFloat(value);
    return Number.isFinite(n) ? n : null;   // empty or NaN in the database → null
}

function formatPrices(book) {
    const parts = [];
    if (book.pb !== null) parts.push(`CAD ${book.pb.toFixed(2)} paperback`);
    if (book.hc !== null) parts.push(`CAD ${book.hc.toFixed(2)} hardcover`);
    return parts.join(' · ');
}

// pub_date is free text; normalise "2025/04/21" to "2025-04-21"
function formatDate(value) {
    return String(value || '').trim().replace(/^(\d{4})\/(\d{2})\/(\d{2})$/, '$1-$2-$3');
}

// Quill HTML → plain text paragraphs
function htmlToText(html) {
    return String(html || '')
        .replace(/<br\s*\/?>/gi, '\n')
        .replace(/<\/(p|div|h[1-6]|li)>/gi, '\n')
        .replace(/<li[^>]*>/gi, '- ')
        .replace(/<[^>]+>/g, '')
        .replace(/&nbsp;/g, ' ').replace(/&amp;/g, '&').replace(/&lt;/g, '<')
        .replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&#39;|&apos;/g, "'")
        .split('\n').map(line => line.trim()).filter(Boolean).join('\n\n');
}

function truncate(text, max) {
    if (text.length <= max) return text;
    return text.slice(0, max).replace(/\s+\S*$/, '') + ' …';
}

function escapeHtml(text) {
    return String(text ?? '')
        .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
        .replace(/"/g, '&quot;').replace(/'/g, '&#39;');
}

// Same rule as normalizeCover() in ui.js, but absolute for meta tags
function coverUrl(cover) {
    if (!cover) return '';
    if (/^https?:\/\//.test(cover)) return cover;
    if (cover.startsWith('data:')) return '';   // data URLs are too large for meta tags
    return `${SITE}${cover.startsWith('/') ? '' : '/'}${cover}`;
}

// Amazon link set by the owner in Manage Books; otherwise an Amazon search by ISBN or title
function amazonLink(book) {
    if (book.amazon_url && /^https?:\/\//.test(book.amazon_url)) {
        return { url: book.amazon_url, label: 'Buy on Amazon', exact: true };
    }
    const query = encodeURIComponent(book.isbn || book.title || '');
    return { url: `https://www.amazon.ca/s?k=${query}`, label: 'Search on Amazon', exact: false };
}

function seriesOf(book) {
    return SERIES.find(s => (book.categories || []).includes(s)) || OTHER_SERIES;
}

// Same A–Z idea as the website: Chinese compared by pinyin
const collator = new Intl.Collator('en', { sensitivity: 'base', ignorePunctuation: true, numeric: true });
function sortKey(text) {
    const t = String(text || '');
    if (!pinyinFn || !/[\u3400-\u9fff]/.test(t)) return t.toLowerCase();
    const chars = Array.from(t);
    const syllables = pinyinFn(t, { toneType: 'none', type: 'array' });
    if (syllables.length !== chars.length) return t.toLowerCase();
    return chars.map((ch, i) => /[\u3400-\u9fff]/.test(ch) ? syllables[i] + ' ' : ch).join('').toLowerCase();
}
function byTitle(a, b) {
    return collator.compare(sortKey(a.title), sortKey(b.title));
}

// "English, français, 中文" → ["en", "fr", "zh"]
const LANGUAGE_CODES = { english: 'en', 'français': 'fr', francais: 'fr', french: 'fr', '中文': 'zh', chinese: 'zh' };
function languageCodes(language) {
    return String(language || '').split(/[,，/]/)
        .map(s => LANGUAGE_CODES[s.trim().toLowerCase()])
        .filter(Boolean);
}

const AVAILABILITY = {
    'in stock': 'https://schema.org/InStock',
    'out of stock': 'https://schema.org/OutOfStock',
    'pre-order': 'https://schema.org/PreOrder',
};

// ── books.md ──────────────────────────────────────────────────────────────────
function bookEntryMd(book) {
    const lines = [`### ${book.title}`, ''];
    const add = (label, value) => { if (value) lines.push(`- ${label}: ${value}`); };

    add('Author', book.author);
    if (book.author_fr && book.author_fr !== book.author) add('Author (French)', book.author_fr);
    if (book.title_fr && book.title_fr !== book.title) add('French title', book.title_fr);
    add('Language', book.language);
    add('Published', formatDate(book.pub_date));
    add('Publisher', book.publisher || 'Acer Books Canada');
    add('ISBN', book.isbn);
    add('Pages', book.pages);
    add('Price', formatPrices(book));
    add('Availability', book.stock_status);
    add('Book page', bookPageUrl(book));
    const amazon = amazonLink(book);
    add(amazon.label, amazon.url);

    const description = htmlToText(book.description);
    if (description) lines.push('', truncate(description, DESCRIPTION_MAX_CHARS));
    return lines.join('\n');
}

function buildBooksMd(books, today) {
    const groups = new Map([...SERIES, OTHER_SERIES].map(s => [s, []]));
    books.forEach(b => groups.get(seriesOf(b)).push(b));

    const sections = [];
    for (const [series, list] of groups) {
        if (list.length === 0) continue;
        list.sort(byTitle);
        sections.push(`## ${series} (${list.length})\n\n${list.map(bookEntryMd).join('\n\n')}`);
    }

    return [
        '# Acer Books Canada — Book Catalogue',
        '',
        `> All ${books.length} titles published by Acer Books Canada, an independent publisher in Montréal, Québec. ` +
        'Prices are in Canadian dollars (CAD). Books are sold on Amazon; each entry links to its Amazon page or an Amazon search.',
        '',
        `Generated from the publisher's database on ${today}.`,
        '',
        sections.join('\n\n'),
        '',
    ].join('\n');
}

// ── llms.txt ──────────────────────────────────────────────────────────────────
function buildLlmsTxt(books, today) {
    const counts = SERIES
        .map(s => [s, books.filter(b => seriesOf(b) === s).length])
        .filter(([, n]) => n > 0)
        .map(([s, n]) => `${s} (${n})`)
        .join(', ');

    return [
        '# Acer Books Canada',
        '',
        '> Acer Books Canada is an independent publisher based in Montréal, Québec, founded by translator and scholar Tao Zhijian, PhD. ' +
        "It publishes poetry, fiction, essays, literary translation and children's art books in Chinese, English and French, " +
        'distributed worldwide through Amazon and bookstores including Harvard Book Store, Hatchards, Barnes & Noble, Kraina Książek and Kinokuniya.',
        '',
        `- The catalogue has ${books.length} titles in these series: ${counts}.`,
        '- Books are purchased on Amazon; each catalogue entry links to its Amazon page.',
        '- Prices are in Canadian dollars (CAD).',
        '- Many titles are bilingual (Chinese–English) or trilingual (Chinese–English–French).',
        '- The website (acerbooks.ca) is in English and French; the Markdown files below have the same information as plain text.',
        '',
        '## Catalogue',
        '',
        `- [Book catalogue](${SITE}/books.md): every title with author, language, publication date, series, ISBN, price, description and Amazon link (updated ${today})`,
        '',
        '## Publisher',
        '',
        `- [About Acer Books](${SITE}/about.md): founder, editorial focus and distribution`,
        '',
        '## Optional',
        '',
        `- [All books (website)](${SITE}/books): browsable catalogue with search and filters`,
        `- [News & events (website)](${SITE}/news): readings, launches and events (needs JavaScript)`,
        '',
    ].join('\n');
}

// ── Static HTML pages (built from index.html) ─────────────────────────────────
// Replaces the inner HTML of the first element with the given id.
// Only used on elements that are empty in index.html.
function fillById(html, id, innerHtml) {
    const re = new RegExp(`(<([a-z0-9]+)\\b[^>]*\\bid="${id}"[^>]*>)([\\s\\S]*?)(</\\2>)`);
    if (!re.test(html)) {
        console.warn(`template: #${id} not found in index.html`);
        return html;
    }
    return html.replace(re, (m, open, tag, inner, close) => `${open}${innerHtml}${close}`);
}

// Changes the inline display style of a top-level page container
function setDisplay(html, id, display) {
    return html.replace(new RegExp(`<div id="${id}"[^>]*>`), `<div id="${id}" style="display: ${display};">`);
}

// Page lives at /book/<slug>: relative asset paths (style.css, main.js) must become absolute
function absolutizePaths(html) {
    return html.replace(/\b(href|src)="(?!https?:|\/|#|data:|mailto:|tel:|javascript:)([^"]+)"/g, '$1="/$2"');
}

function headTags({ title, description, canonical, image, type, jsonLd }) {
    const tags = [
        GENERATED_MARKER,
        `<meta name="description" content="${escapeHtml(description)}">`,
        `<link rel="canonical" href="${canonical}">`,
        `<meta property="og:type" content="${type}">`,
        `<meta property="og:site_name" content="Acer Books Canada">`,
        `<meta property="og:title" content="${escapeHtml(title)}">`,
        `<meta property="og:description" content="${escapeHtml(description)}">`,
        `<meta property="og:url" content="${canonical}">`,
    ];
    if (image) tags.push(`<meta property="og:image" content="${escapeHtml(image)}">`);
    if (jsonLd) {
        // "<" escaped so text in the data can never close the script tag
        tags.push(`<script type="application/ld+json">${JSON.stringify(jsonLd).replace(/</g, '\\u003c')}</script>`);
    }
    return tags.map(t => `    ${t}`).join('\n');
}

function withHead(html, title, extraHead) {
    return html
        .replace(/<title>[\s\S]*?<\/title>/, `<title>${escapeHtml(title)}</title>`)
        .replace('</head>', `${extraHead}\n</head>`);
}

function bookJsonLd(book) {
    const url = bookPageUrl(book);
    const amazon = amazonLink(book);
    const availability = AVAILABILITY[String(book.stock_status || '').toLowerCase()] || 'https://schema.org/InStock';
    const offer = (price, format) => ({
        '@type': 'Offer',
        price: price.toFixed(2),
        priceCurrency: 'CAD',
        availability,
        url: amazon.exact ? amazon.url : url,
        itemOffered: { '@type': 'Book', bookFormat: `https://schema.org/${format}` },
    });
    const offers = [];
    if (book.pb !== null) offers.push(offer(book.pb, 'Paperback'));
    if (book.hc !== null) offers.push(offer(book.hc, 'Hardcover'));
    const langs = languageCodes(book.language);

    const data = {
        '@context': 'https://schema.org',
        '@type': 'Book',
        name: book.title,
        url,
        author: { '@type': 'Person', name: book.author },
        publisher: { '@type': 'Organization', name: book.publisher || 'Acer Books Canada', url: SITE },
    };
    if (book.title_fr && book.title_fr !== book.title) data.alternateName = book.title_fr;
    if (book.isbn) data.isbn = book.isbn;
    if (toNumber(book.pages)) data.numberOfPages = toNumber(book.pages);
    if (/^\d{4}(-\d{2}(-\d{2})?)?$/.test(formatDate(book.pub_date))) data.datePublished = formatDate(book.pub_date);
    if (langs.length) data.inLanguage = langs.length === 1 ? langs[0] : langs;
    if (book.series !== OTHER_SERIES) data.isPartOf = { '@type': 'BookSeries', name: book.series };
    if (coverUrl(book.cover)) data.image = coverUrl(book.cover);
    const text = htmlToText(book.description);
    if (text) data.description = truncate(text, 1000);
    if (offers.length) data.offers = offers.length === 1 ? offers[0] : offers;
    return data;
}

function buildBookPage(template, book) {
    // Same title format as updateMetaTags() in ui.js
    const title = `${book.title} by ${book.author} | Acer Books`;
    const text = htmlToText(book.description);
    const description = truncate(
        text ? text.replace(/\s+/g, ' ') : `${book.title} by ${book.author}, published by Acer Books Canada (Montréal).`,
        META_DESCRIPTION_MAX_CHARS);
    const cover = coverUrl(book.cover);
    const price = book.pb ?? book.hc;

    let html = withHead(template, title, headTags({
        title, description, canonical: bookPageUrl(book), image: cover, type: 'book', jsonLd: bookJsonLd(book),
    }));

    // Show the detail page instead of the homepage, already filled with the book.
    // renderBookDetail() in ui.js fills the same elements again when JavaScript runs.
    html = setDisplay(html, 'mainContent', 'none');
    html = setDisplay(html, 'bookDetailPage', 'block');
    if (cover) {
        html = html.replace(/<div id="detailCover"([^>]*)>/,
            `<div id="detailCover"$1 style="background-image: url('${escapeHtml(cover)}');">`);
    }
    html = fillById(html, 'detailTitle', escapeHtml(book.title));
    html = fillById(html, 'detailAuthor', escapeHtml(book.author));
    if (price !== null) html = fillById(html, 'detailPrice', `$${price.toFixed(2)}`);
    html = fillById(html, 'detailDescription', book.description || '');   // owner-written HTML, same as innerHTML in ui.js
    html = fillById(html, 'detailAuthorBio', book.author_bio || '');
    html = fillById(html, 'detailCategories',
        (book.categories || []).map(c => `<span class="category-tag">${escapeHtml(c)}</span>`).join(''));
    html = fillById(html, 'detailIsbn', escapeHtml(book.isbn || ''));
    html = fillById(html, 'detailPublisher', escapeHtml(book.publisher || 'Acer Books'));
    html = fillById(html, 'detailPubDate', escapeHtml(book.pub_date || ''));
    html = fillById(html, 'detailPages', escapeHtml(book.pages || ''));
    html = fillById(html, 'detailLanguage', escapeHtml(book.language || ''));

    return absolutizePaths(html);
}

function buildBooksPage(template, books) {
    const title = 'All Books | Acer Books';
    const description = `All ${books.length} titles from Acer Books Canada, an independent publisher in Montréal: poetry, fiction, essays, translation and children's art books in Chinese, English and French.`;

    let html = withHead(template, title, headTags({
        title, description, canonical: `${SITE}/books`, image: '', type: 'website', jsonLd: null,
    }));
    html = setDisplay(html, 'mainContent', 'none');
    html = setDisplay(html, 'booksPage', 'block');

    // Plain links so crawlers can reach every book page; renderAllBooks() replaces them with cards
    const links = [...books].filter(b => b.slug).sort(byTitle).map(b =>
        `<li><a href="/book/${b.slug}">${escapeHtml(b.title)}</a> — ${escapeHtml(b.author)}</li>`);
    html = fillById(html, 'booksGrid', `<ul class="static-book-links">${links.join('')}</ul>`);

    return absolutizePaths(html);
}

function buildSitemap(books) {
    const urls = [`${SITE}/`, `${SITE}/books`, ...books.filter(b => b.slug).map(bookPageUrl)];
    return [
        '<?xml version="1.0" encoding="UTF-8"?>',
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
        ...urls.map(u => `  <url><loc>${escapeHtml(u)}</loc></url>`),
        '</urlset>',
        '',
    ].join('\n');
}

// ── File helpers ──────────────────────────────────────────────────────────────
async function exists(path) {
    try { await access(path); return true; } catch { return false; }
}

// Writes the file only when the content changed, ignoring the "updated/generated on" date,
// so the daily run does not create a commit when no book changed.
async function writeIfChanged(path, content) {
    const stripDate = s => s.replace(/\d{4}-\d{2}-\d{2}(?=[).])/g, '');
    let old = null;
    try { old = await readFile(path, 'utf8'); } catch { /* new file */ }
    if (old !== null && stripDate(old) === stripDate(content)) return false;
    await writeFile(path, content, 'utf8');
    console.log(`written:   ${path}`);
    return true;
}

// Deletes book/*.html pages generated earlier for books that no longer exist
async function removeStaleBookPages(keepFiles) {
    let files = [];
    try { files = await readdir(`${OUTPUT_DIR}/book`); } catch { return; }
    for (const file of files) {
        if (!file.endsWith('.html') || keepFiles.has(file)) continue;
        const path = `${OUTPUT_DIR}/book/${file}`;
        if ((await readFile(path, 'utf8')).includes(GENERATED_MARKER)) {
            await unlink(path);
            console.log(`removed:   ${path}`);
        }
    }
}

// ── Main ──────────────────────────────────────────────────────────────────────
const rawBooks = (await loadBooks()).filter(b => b && b.title);
if (rawBooks.length === 0) throw new Error('No books returned — not overwriting the existing files.');

const books = rawBooks.map(b => ({
    ...b,
    slug: bookSlug(b.title),
    pb: toNumber(b.price),
    hc: toNumber(b.price_hardcover),
    series: seriesOf(b),
}));

// Two books with the same slug would share one URL on the website too
const slugCount = new Map();
books.forEach(b => b.slug && slugCount.set(b.slug, (slugCount.get(b.slug) || 0) + 1));
for (const [slug, n] of slugCount) if (n > 1) console.warn(`warning: ${n} books share the slug "${slug}"`);

const today = new Date().toISOString().slice(0, 10);

// Markdown for AI agents
await writeIfChanged(`${OUTPUT_DIR}/books.md`, buildBooksMd(books, today));
await writeIfChanged(`${OUTPUT_DIR}/llms.txt`, buildLlmsTxt(books, today));

// Static HTML pages for search engines
if (await exists(TEMPLATE_FILE)) {
    const template = await readFile(TEMPLATE_FILE, 'utf8');
    await mkdir(`${OUTPUT_DIR}/book`, { recursive: true });
    const keep = new Set();
    for (const book of books) {
        if (!book.slug) { console.warn(`no slug, skipped: ${book.title}`); continue; }
        keep.add(`${book.slug}.html`);
        await writeIfChanged(`${OUTPUT_DIR}/book/${book.slug}.html`, buildBookPage(template, book));
    }
    await removeStaleBookPages(keep);
    await writeIfChanged(`${OUTPUT_DIR}/books.html`, buildBooksPage(template, books));
} else {
    console.warn(`${TEMPLATE_FILE} not found — static pages skipped.`);
}

await writeIfChanged(`${OUTPUT_DIR}/sitemap.xml`, buildSitemap(books));

if (!(await exists(`${OUTPUT_DIR}/robots.txt`))) {
    await writeFile(`${OUTPUT_DIR}/robots.txt`, `User-agent: *\nAllow: /\n\nSitemap: ${SITE}/sitemap.xml\n`);
    console.log(`written:   ${OUTPUT_DIR}/robots.txt`);
} else {
    console.log(`robots.txt exists — make sure it contains: Sitemap: ${SITE}/sitemap.xml`);
}

if (!(await exists(`${OUTPUT_DIR}/.nojekyll`))) {
    await writeFile(`${OUTPUT_DIR}/.nojekyll`, '');
    console.log(`written:   ${OUTPUT_DIR}/.nojekyll`);
}

console.log(`Done: ${books.length} books.`);
